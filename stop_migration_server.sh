#!/bin/bash

# =============================================================================
# سكريبت إيقاف خادم نظام نقل البيانات
# Migration System Server Stopper
# =============================================================================

echo "🛑 إيقاف خادم نظام نقل البيانات..."

# إنهاء الخادم
if pkill -f "php -S 127.0.0.1:8002"; then
    echo "✅ تم إيقاف الخادم بنجاح!"
else
    echo "ℹ️  لم يتم العثور على خادم يعمل على البورت 8002"
fi

echo ""
echo "📊 حالة الخوادم الحالية:"
ps aux | grep -E "php.*127\.0\.0\.1" | grep -v grep || echo "   لا توجد خوادم PHP تعمل"
