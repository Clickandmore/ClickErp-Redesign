const {test}=require('node:test');
const assert=require('node:assert/strict');
const {readFileSync}=require('node:fs');
const vm=require('node:vm');
test('visit editor increments by 15 minutes, prices the difference, and resets between modes',async()=>{
    const nodes={},node=id=>nodes[id] ||= {classList:{toggle(){}},addEventListener(){}};
    const names=['action','visit_ids[]','hours','expected_price','expected_hours','price','duration_price_adjustment','ignore_hour_caps','ignore_break'];
    const form=node('visit-edit-form');form.elements=Object.fromEntries(names.map(n=>[n,{}]));form.reset=()=>{};form.reportValidity=()=>true;form.getAttribute=()=>'/orders/1/operations';form.action={};
    const modal=node('visit-edit-modal');modal.querySelector=selector=>node(selector);
    let opened=0;
    const context={document:{getElementById:node,body:{appendChild(){}}},window:{hourlyVisitEditorData:{visits:{1:{id:1,price:400,hours:4,date:'Tomorrow',workers:'Worker',status:'Scheduled'}},labels:{hour:'Hr',minute:'min',added:'added',removed:'removed'}}},bootstrap:{Modal:{getOrCreateInstance:()=>({show(){opened++;}})}}};
    let submitted,reloaded=false;
    context.FormData=class {};
    context.fetch=async url=>{submitted=url;return {ok:true,json:async()=>({})};};
    context.location={reload(){reloaded=true;}};
    vm.runInNewContext(readFileSync('public/admin/assets/js/hourly-visit-edit.js','utf8'),context);
    context.window.openHourlyVisitEditor('duration',1);
    node('ve-plus').onclick();
    assert.equal(form.elements.hours.value,4.25);
    assert.equal(form.elements.duration_price_adjustment.value,'25.00');
    assert.equal(node('ve-total').textContent,'425.00');
    form.elements.duration_price_adjustment.value='10';form.elements.duration_price_adjustment.oninput();
    assert.equal(node('ve-total').textContent,'410.00');
    node('ve-minus').onclick();assert.equal(form.elements.hours.value,4);
    assert.equal(form.elements.ignore_break.disabled,true);
    context.window.openHourlyVisitEditor('price',1);
    assert.equal(form.elements.price.disabled,false);
    assert.equal(form.elements.hours.disabled,true);
    assert.equal(node('ve-current').value,'400.00');assert.equal(opened,2);
    await form.onsubmit({preventDefault(){}});
    assert.equal(submitted,'/orders/1/operations');assert.equal(reloaded,true);
});
