<?php

namespace App\Support;

use Illuminate\Database\QueryException;
use Throwable;

class ContractCreationError
{
    public static function message(Throwable $error): string
    {
        $detail = $error->getMessage();

        if ($error instanceof QueryException) {
            $code = (int) ($error->errorInfo[1] ?? 0);

            if ($code === 1054 && preg_match("/Unknown column '([a-zA-Z0-9_.]+)'/", $detail, $matches)) {
                return 'قاعدة البيانات تحتاج إلى تحديث: الحقل ' . $matches[1] . ' غير موجود. يرجى إبلاغ مسؤول النظام لتشغيل التحديثات.';
            }

            if ($code === 1146) {
                return 'أحد جداول قاعدة البيانات المطلوبة غير موجود. يرجى إبلاغ مسؤول النظام لتشغيل التحديثات.';
            }

            if ($code === 1062) {
                return 'توجد بيانات مكررة تتعارض مع سجل موجود. يرجى مراجعة بيانات العميل والعقد.';
            }

            if (in_array($code, [1451, 1452], true)) {
                return 'تعذر ربط العقد بأحد السجلات المختارة. يرجى تحديث الصفحة والتحقق من العميل والعاملة والموظف المسؤول.';
            }

            if (in_array($code, [1048, 1364, 1406, 1366, 1292], true)) {
                return 'إحدى القيم المطلوبة مفقودة أو غير صالحة أو تتجاوز الطول المسموح في قاعدة البيانات. يرجى مراجعة بيانات العقد.';
            }

            if (stripos($detail, 'No space left on device') !== false || $code === 1114) {
                return 'لا توجد مساحة كافية في تخزين قاعدة البيانات. يرجى إبلاغ مسؤول النظام لتوفير مساحة.';
            }

            if (in_array($code, [1205, 1213], true)) {
                return 'قاعدة البيانات مشغولة بسبب عمليات متزامنة. يرجى المحاولة بعد قليل.';
            }

            if (in_array($code, [1040, 1045, 2002, 2003, 2006, 2013], true)) {
                return 'تعذر الاتصال بقاعدة البيانات أو انقطع الاتصال بها. يرجى إبلاغ مسؤول النظام والتحقق من حفظ العقد قبل إعادة المحاولة.';
            }

            return 'حدث خطأ في قاعدة البيانات أثناء حفظ العقد. يرجى إبلاغ مسؤول النظام بمرجع الخطأ لمعرفة التفاصيل.';
        }

        return 'حدث خطأ داخلي أثناء معالجة العقد. يرجى إبلاغ مسؤول النظام بمرجع الخطأ لمعرفة السبب والتحقق من حفظ العقد قبل إعادة المحاولة.';
    }
}
